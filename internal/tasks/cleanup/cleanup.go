// Package cleanup implements the age-based file cleanup behind both the
// "logclean" and "tempclean" task types.
//
// One implementation, two presets. The risk profile of deleting a log is not
// the same as deleting a temp file, so the defaults differ, but the mechanics
// must not: two copies of a deletion routine is two places for a safety check to
// go missing.
package cleanup

import (
	"context"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"syscall"
	"time"

	"github.com/jhuancz/cronkite/internal/config"
	"github.com/jhuancz/cronkite/internal/durationx"
	"github.com/jhuancz/cronkite/internal/fsx"
	"github.com/jhuancz/cronkite/internal/report"
	"github.com/jhuancz/cronkite/internal/task"
)

type preset struct {
	olderThan string
	maxDepth  int
}

var presets = map[string]preset{
	// Logs are the evidence of what happened on a machine: be conservative.
	"logclean": {olderThan: "30d", maxDepth: 4},
	// Temp trees are deep, noisy, and regenerated by definition.
	"tempclean": {olderThan: "7d", maxDepth: 8},
}

// Task removes files older than a retention window under confined roots.
type Task struct {
	name       string
	typ        string
	older      time.Duration
	olderText  string
	maxDepth   int
	rmDirs     bool
	guard      *fsx.Guard
	unresolved []string
}

// New validates the task configuration and opens its roots.
func New(cfg config.Task) (*Task, error) {
	p, ok := presets[cfg.Type]
	if !ok {
		return nil, fmt.Errorf("unknown task type %q", cfg.Type)
	}

	t := &Task{
		name:      cfg.Name,
		typ:       cfg.Type,
		olderText: p.olderThan,
		maxDepth:  p.maxDepth,
		rmDirs:    true,
	}

	older, err := durationx.Parse(p.olderThan)
	if err != nil {
		return nil, fmt.Errorf("task %s: built-in default: %w", cfg.Name, err)
	}
	if cfg.OlderThan != "" {
		older, err = durationx.Parse(cfg.OlderThan)
		if err != nil {
			return nil, fmt.Errorf("task %s: older_than: %w", cfg.Name, err)
		}
		t.olderText = cfg.OlderThan
	}
	t.older = older

	if cfg.MaxDepth != nil {
		t.maxDepth = *cfg.MaxDepth
	}
	if cfg.RemoveEmptyDirs != nil {
		t.rmDirs = *cfg.RemoveEmptyDirs
	}

	guard, err := fsx.NewGuard(cfg.Roots, cfg.Protect)
	if err != nil {
		return nil, fmt.Errorf("task %s: %w", cfg.Name, err)
	}
	t.guard = guard
	t.unresolved = cfg.UnresolvedRoots
	return t, nil
}

// Name implements task.Runner.
func (t *Task) Name() string { return t.name }

// Type implements task.Runner.
func (t *Task) Type() string { return t.typ }

// Close releases the confined root handles.
func (t *Task) Close() error { return t.guard.Close() }

// Plan walks every root and collects the candidates: regular files whose
// modification time is older than the retention window, minus anything
// protected.
func (t *Task) Plan(ctx context.Context, env task.Env) (*task.Plan, error) {
	plan := &task.Plan{}
	cutoff := env.Now.Add(-t.older)

	for _, unset := range t.unresolved {
		plan.Notes = append(plan.Notes, fmt.Sprintf("root %q is not defined in this environment; skipped", unset))
	}
	for _, missing := range t.guard.Missing() {
		plan.Notes = append(plan.Notes, "root does not exist: "+missing)
	}

	for _, root := range t.guard.Roots() {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		err := root.Walk(t.maxDepth, func(abs, _ string, d fs.DirEntry) error {
			if err := ctx.Err(); err != nil {
				return err
			}

			if d.IsDir() {
				if t.rmDirs && !t.guard.Protected(abs) {
					plan.Dirs = append(plan.Dirs, abs)
				}
				return nil
			}

			// Symlinks and special files are never removed: cronkite cannot
			// prove what they point at, and a stale symlink is cheaper to keep
			// than a security incident to explain.
			if d.Type()&fs.ModeSymlink != 0 {
				plan.Skipped = append(plan.Skipped, task.Action{Path: abs, Reason: "symlink"})
				return nil
			}
			if !d.Type().IsRegular() {
				plan.Skipped = append(plan.Skipped, task.Action{Path: abs, Reason: "not_a_regular_file"})
				return nil
			}

			info, err := d.Info()
			if err != nil {
				plan.Notes = append(plan.Notes, fmt.Sprintf("stat %s: %v", abs, err))
				return nil
			}
			if !info.ModTime().Before(cutoff) {
				return nil
			}

			reason := "older_than_" + t.olderText
			if t.guard.Protected(abs) {
				plan.Skipped = append(plan.Skipped, task.Action{Path: abs, Size: info.Size(), Reason: "protected"})
				return nil
			}
			plan.Actions = append(plan.Actions, task.Action{
				Path:   abs,
				Kind:   report.ActionDelete,
				Size:   info.Size(),
				Reason: reason,
			})
			return nil
		}, func(abs string, err error) {
			plan.Notes = append(plan.Notes, fmt.Sprintf("skip %s: %v", abs, err))
		})
		if err != nil {
			return nil, err
		}
	}

	// Deepest first, so a directory is empty by the time it is considered.
	sort.SliceStable(plan.Dirs, func(i, j int) bool {
		return strings.Count(plan.Dirs[i], string(filepath.Separator)) >
			strings.Count(plan.Dirs[j], string(filepath.Separator))
	})
	return plan, nil
}

// Apply executes the plan.
//
// Locked and forbidden paths are recorded as skipped, not as failures: a log
// file held open by another service is an expected condition, not news. The
// exception is a task where nothing at all could be removed, which is a
// configuration or privilege problem and must be visible.
func (t *Task) Apply(ctx context.Context, plan *task.Plan, env task.Env) (*task.Result, error) {
	res := &task.Result{}
	forbidden := 0

	for _, action := range plan.Actions {
		if err := ctx.Err(); err != nil {
			return res, err
		}
		if err := t.guard.Remove(action.Path); err != nil {
			switch {
			case errors.Is(err, fsx.ErrProtected):
				res.Skipped = append(res.Skipped, withReason(action, "protected"))
			case isLockedOrForbidden(err):
				res.Skipped = append(res.Skipped, withReason(action, "locked_or_forbidden"))
				forbidden++
			default:
				res.Failed = append(res.Failed, task.Failure{Path: action.Path, Err: err})
			}
			continue
		}
		res.Done = append(res.Done, action)
	}

	if t.rmDirs {
		for _, dir := range plan.Dirs {
			if err := ctx.Err(); err != nil {
				return res, err
			}
			if err := t.guard.Remove(dir); err != nil {
				// A non-empty directory is the expected outcome, not an error.
				continue
			}
			res.DirsRemoved++
		}
	}

	if len(res.Done) == 0 && forbidden > 0 {
		res.Failed = append(res.Failed, task.Failure{
			Path: t.roots(),
			Err:  fmt.Errorf("no candidate could be removed (%d locked or forbidden): check that cronkite runs as a user allowed to delete inside the configured roots", forbidden),
		})
	}
	return res, nil
}

func (t *Task) roots() string {
	var roots []string
	for _, r := range t.guard.Roots() {
		roots = append(roots, r.Dir())
	}
	return strings.Join(roots, ", ")
}

func withReason(a task.Action, reason string) task.Action {
	a.Reason = reason
	a.Kind = ""
	return a
}

// isLockedOrForbidden distinguishes "this file is in use" from "this delete is
// broken". Both Windows sharing violations and Unix busy/permission errors are
// expected on live systems.
func isLockedOrForbidden(err error) bool {
	if errors.Is(err, fs.ErrPermission) || errors.Is(err, os.ErrPermission) {
		return true
	}
	var errno syscall.Errno
	if errors.As(err, &errno) {
		switch uintptr(errno) {
		case 16, // EBUSY
			26, // ETXTBSY
			32, // ERROR_SHARING_VIOLATION (Windows)
			33: // ERROR_LOCK_VIOLATION (Windows)
			return true
		}
	}
	return false
}
